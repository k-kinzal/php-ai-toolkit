final class BuiltinExtensionTest extends TestCase
{
    public function testRegisterUsesOnlyStructuresAndOrdinaryPolicies(): void
    {
        $configuration = new \Guard\Config\Configuration('/unused', [new \Guard\Extension\PolicyBinding('example', new \Guard\Policy\FieldConstraints([]))]);
        $registry = new \Guard\Extension\Registry();
        (new \Guard\Extension\BuiltinExtension($configuration))->register($registry);
        self::assertSame(['example'], array_map(static fn (\Guard\Extension\PolicyBinding $binding): string => $binding->id, $registry->policies()));
        self::assertArrayHasKey('php.tokens', $registry->structures());
        self::assertArrayHasKey('markdown.headings', $registry->structures());
        self::assertArrayHasKey('xml', $registry->structures());
    }
}
